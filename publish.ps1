<#
.SYNOPSIS
  Builds a self-contained Reel Player release (no .NET install needed on the target PC).
.EXAMPLE
  .\publish.ps1                 # win-x64 → dist\ReelPlayer-win-x64\ and dist\ReelPlayer-win-x64.zip
  .\publish.ps1 -Runtime win-arm64
  .\publish.ps1 -Installer      # also compiles installer\ReelPlayer.iss with Inno Setup (iscc on PATH)
  .\publish.ps1 -Layout Folder  # plain folder: ~25% less RAM and 2x faster start, ~70 MB more disk
.PARAMETER Layout
  SingleFile (default): ReelPlayer.exe bundles the .NET runtime compressed. Smallest on disk (~145 MB with libVLC).
  Folder: runtime as loose files. Assemblies are memory-mapped instead of unpacked into RAM, so it uses less
  memory (~300 MB vs ~385 MB playing 720p maximized on 4K) and starts faster, but takes ~215 MB on disk.
  Functionality is identical.
#>
param(
    [ValidateSet('win-x64', 'win-x86', 'win-arm64')]
    [string]$Runtime = 'win-x64',
    [ValidateSet('SingleFile', 'Folder')]
    [string]$Layout = 'SingleFile',
    [switch]$Installer,
    [switch]$SkipTests
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$out = Join-Path $root "dist\ReelPlayer-$Runtime"
$zip = "$out.zip"

if (-not $SkipTests) {
    Write-Host '== Unit tests' -ForegroundColor Cyan
    dotnet test (Join-Path $root 'tests\ReelPlayer.Core.Tests') -c Release --nologo
    if ($LASTEXITCODE) { throw 'Unit tests failed.' }
}

Write-Host "== Publishing $Runtime ($Layout)" -ForegroundColor Cyan
if (Test-Path $out) { Remove-Item $out -Recurse -Force }
# SingleFile: uncompressed bundle so .NET memory-maps assemblies directly instead of zlib-decompressing them
# into RAM on every launch (~250-350 ms faster start and ~80 MB less RAM; the .zip is still compressed).
# Native WPF DLLs stay next to the exe instead of being extracted to %TEMP%.
$layoutArgs = if ($Layout -eq 'SingleFile') {
    '-p:PublishSingleFile=true', '-p:EnableCompressionInSingleFile=false', '-p:IncludeNativeLibrariesForSelfExtract=false'
} else { @() }
dotnet publish (Join-Path $root 'src\ReelPlayer.App') -c Release -r $Runtime --self-contained true `
    @layoutArgs -p:PublishReadyToRun=true -p:DebugType=none -o $out --nologo
if ($LASTEXITCODE) { throw 'dotnet publish failed.' }

# libVLC must live next to the exe (it cannot be packed into the single file).
$arch = $Runtime.Split('-')[1]
$libvlc = Join-Path $out "libvlc\win-$arch"
if (-not (Test-Path (Join-Path $libvlc 'libvlc.dll'))) { throw "libVLC was not copied to $libvlc." }

# Plugin cache: without plugins\plugins.dat libVLC loads all ~250 plugin DLLs at startup to read their
# descriptions (~20 MB more memory and slower start). libVLC writes the cache itself; it must be generated by a
# process of the same architecture, so other architectures ship without it (libVLC then scans, as before).
if ($Runtime -eq 'win-x64' -and [Environment]::Is64BitOperatingSystem -and $env:PROCESSOR_ARCHITECTURE -eq 'AMD64') {
    Write-Host '== Generating libVLC plugin cache' -ForegroundColor Cyan
    dotnet run --project (Join-Path $root 'tools\FormatProbe') -c Release -- --libvlc $libvlc --cache-gen
    if ($LASTEXITCODE) { throw 'Plugin cache generation failed.' }
} else {
    Write-Warning "Skipping libVLC plugin cache for $Runtime (needs a matching-architecture host)."
}

Copy-Item (Join-Path $root 'THIRD-PARTY-NOTICES.txt') $out -Force
Copy-Item (Join-Path $root 'README.md') $out -Force -ErrorAction SilentlyContinue

if (Test-Path $zip) { Remove-Item $zip -Force }
Compress-Archive -Path (Join-Path $out '*') -DestinationPath $zip -CompressionLevel Optimal

$size = '{0:N0} MB' -f ((Get-ChildItem $out -Recurse | Measure-Object Length -Sum).Sum / 1MB)
Write-Host "== Done: $out ($size), $zip" -ForegroundColor Green

if ($Installer) {
    $iscc = (Get-Command iscc -ErrorAction SilentlyContinue).Source
    if (-not $iscc) {
        $default = "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe"
        if (Test-Path $default) { $iscc = $default } else { throw 'Inno Setup (iscc) not found: winget install JRSoftware.InnoSetup' }
    }
    & $iscc "/DSourceDir=$out" "/DArch=$arch" (Join-Path $root 'installer\ReelPlayer.iss')
    if ($LASTEXITCODE) { throw 'Installer build failed.' }
}
